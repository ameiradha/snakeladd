import React, { useState, useEffect } from 'react';
import { Quiz, Question, QuestionType, Difficulty } from '../types';
import { checkAIStatus, requestAIGenerateQuiz, AIStatusResponse } from '../services/ai';
import { Sparkles, Loader2, AlertCircle, CheckCircle2, Trash2, Edit3, ArrowRight, Save } from 'lucide-react';

interface AIQuizGeneratorProps {
  onSaveQuiz: (quiz: Quiz) => void;
  onCancel: () => void;
}

export const AIQuizGenerator: React.FC<AIQuizGeneratorProps> = ({ onSaveQuiz, onCancel }) => {
  const [aiStatus, setAiStatus] = useState<AIStatusResponse | null>(null);
  const [loadingStatus, setLoadingStatus] = useState(true);

  // Form fields
  const [promptDescription, setPromptDescription] = useState('');
  const [subject, setSubject] = useState('Science');
  const [yearLevel, setYearLevel] = useState('Year 4');
  const [topic, setTopic] = useState('Electricity and Conductors');
  const [language, setLanguage] = useState<'English' | 'Bahasa Melayu'>('English');
  const [count, setCount] = useState(10);
  const [difficulty, setDifficulty] = useState<Difficulty>('Medium');
  const [questionType, setQuestionType] = useState<'MCQ' | 'TRUE_FALSE' | 'SHORT_ANSWER' | 'MIXED'>('MIXED');
  const [curriculumStandard, setCurriculumStandard] = useState('');
  const [includeExplanations, setIncludeExplanations] = useState(true);
  const [includeAlternatives, setIncludeAlternatives] = useState(true);

  // Execution states
  const [isGenerating, setIsGenerating] = useState(false);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);
  const [generatedQuestions, setGeneratedQuestions] = useState<Question[]>([]);
  const [quizTitle, setQuizTitle] = useState('');
  const [isReviewing, setIsReviewing] = useState(false);

  useEffect(() => {
    checkAIStatus()
      .then((res) => {
        setAiStatus(res);
        setLoadingStatus(false);
      })
      .catch(() => {
        setAiStatus({
          available: false,
          model: 'gemini-3.8-flash',
          message: 'Unable to contact AI status endpoint.',
        });
        setLoadingStatus(false);
      });
  }, []);

  const handleGenerate = async () => {
    setIsGenerating(true);
    setErrorMessage(null);

    try {
      const result = await requestAIGenerateQuiz({
        promptDescription,
        subject,
        yearLevel,
        topic,
        language,
        count,
        difficulty,
        questionType,
        curriculumStandard,
        includeExplanations,
        includeAlternatives,
      });

      setGeneratedQuestions(result.questions);
      setQuizTitle(result.title);
      setIsReviewing(true);
    } catch (err: any) {
      setErrorMessage(err.message || 'Failed to generate quiz. Please retry.');
    } finally {
      setIsGenerating(false);
    }
  };

  const handleUpdateQuestion = (index: number, updates: Partial<Question>) => {
    const updated = [...generatedQuestions];
    updated[index] = { ...updated[index], ...updates };
    setGeneratedQuestions(updated);
  };

  const handleDeleteQuestion = (index: number) => {
    setGeneratedQuestions(generatedQuestions.filter((_, i) => i !== index));
  };

  const handleSaveToLibrary = () => {
    if (generatedQuestions.length === 0) {
      alert('Cannot save an empty quiz. Please generate or keep at least one question.');
      return;
    }

    const newQuiz: Quiz = {
      id: `quiz_ai_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`,
      title: quizTitle || `${subject}: ${topic} (${yearLevel})`,
      subject,
      yearLevel,
      topic,
      language,
      description: promptDescription || `Generated by AI for ${yearLevel} ${subject}.`,
      questions: generatedQuestions,
      createdAt: Date.now(),
      updatedAt: Date.now(),
    };

    onSaveQuiz(newQuiz);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-5 bg-slate-900/50 backdrop-blur-sm">
      <div className="relative w-full max-w-4xl max-h-[92vh] flex flex-col bg-white border border-slate-200 rounded-3xl shadow-2xl overflow-hidden">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-slate-200 bg-slate-50">
          <div className="flex items-center gap-2.5">
            <Sparkles className="w-5 h-5 text-amber-500" />
            <h2 className="text-lg font-extrabold text-slate-900">
              {isReviewing ? 'Semak Kuiz Dijana AI (Review)' : 'Penjana Kuiz Berkuasa AI / AI Quiz Generator'}
            </h2>
          </div>
          <button
            type="button"
            onClick={onCancel}
            className="text-xs font-bold text-slate-500 hover:text-slate-800 cursor-pointer"
          >
            Tutup / Close
          </button>
        </div>

        {/* AI Service Status Notification */}
        {!isReviewing && aiStatus && !aiStatus.available && (
          <div className="mx-6 mt-4 p-4 rounded-2xl bg-amber-50 border-2 border-amber-300 text-amber-900 text-xs flex items-start gap-3">
            <AlertCircle className="w-5 h-5 text-amber-600 shrink-0 mt-0.5" />
            <div>
              <span className="font-black block text-sm">Konfigurasi AI Backend Diperlukan</span>
              <p className="mt-0.5 leading-relaxed text-amber-800">
                {aiStatus.message} Anda juga boleh menggunakan Editor Kuiz Manual dan Import Teks yang berfungsi 100% tanpa internet / offline.
              </p>
            </div>
          </div>
        )}

        {/* Content Area */}
        <div className="flex-1 overflow-y-auto p-6">
          {!isReviewing ? (
            /* Generator Form */
            <div className="space-y-4">
              {/* Natural Language Prompt */}
              <div>
                <label className="text-xs font-black text-slate-700 uppercase tracking-wider block mb-1.5">
                  Arahan Bahasa Semulajadi / Prompt (Pilihan):
                </label>
                <textarea
                  value={promptDescription}
                  onChange={(e) => setPromptDescription(e.target.value)}
                  placeholder='cth., "Jana 10 soalan Sains Tahun 4 topik sistem suria dan planet dalam Bahasa Melayu berserta penerangan jawapan."'
                  rows={2}
                  className="w-full bg-slate-50 border-2 border-slate-200 rounded-xl p-3 text-sm text-slate-900 placeholder-slate-400 focus:outline-none focus:border-amber-500 focus:bg-white"
                />
              </div>

              {/* Grid Form Fields */}
              <div className="grid grid-cols-1 sm:grid-cols-2 md:grid-cols-3 gap-4">
                <div>
                  <label className="text-xs font-bold text-slate-600 block mb-1">Mata Pelajaran (Subject)</label>
                  <input
                    type="text"
                    value={subject}
                    onChange={(e) => setSubject(e.target.value)}
                    placeholder="cth. Sains / Science"
                    className="w-full bg-slate-50 border-2 border-slate-200 rounded-xl px-3 py-2 text-sm text-slate-900 focus:outline-none focus:border-amber-500 focus:bg-white"
                  />
                </div>

                <div>
                  <label className="text-xs font-bold text-slate-600 block mb-1">Tahun / Tingkatan (Grade)</label>
                  <select
                    value={yearLevel}
                    onChange={(e) => setYearLevel(e.target.value)}
                    className="w-full bg-slate-50 border-2 border-slate-200 rounded-xl px-3 py-2 text-sm text-slate-900 focus:outline-none focus:border-amber-500 focus:bg-white"
                  >
                    <option value="Year 1">Tahun 1 / Year 1</option>
                    <option value="Year 2">Tahun 2 / Year 2</option>
                    <option value="Year 3">Tahun 3 / Year 3</option>
                    <option value="Year 4">Tahun 4 / Year 4</option>
                    <option value="Year 5">Tahun 5 / Year 5</option>
                    <option value="Year 6">Tahun 6 / Year 6</option>
                  </select>
                </div>

                <div>
                  <label className="text-xs font-bold text-slate-600 block mb-1">Topik / Tajuk (Topic)</label>
                  <input
                    type="text"
                    value={topic}
                    onChange={(e) => setTopic(e.target.value)}
                    placeholder="cth. Elektrik & Litar"
                    className="w-full bg-slate-50 border-2 border-slate-200 rounded-xl px-3 py-2 text-sm text-slate-900 focus:outline-none focus:border-amber-500 focus:bg-white"
                  />
                </div>

                <div>
                  <label className="text-xs font-bold text-slate-600 block mb-1">Bahasa (Language)</label>
                  <select
                    value={language}
                    onChange={(e) => setLanguage(e.target.value as any)}
                    className="w-full bg-slate-50 border-2 border-slate-200 rounded-xl px-3 py-2 text-sm text-slate-900 focus:outline-none focus:border-amber-500 focus:bg-white"
                  >
                    <option value="English">English</option>
                    <option value="Bahasa Melayu">Bahasa Melayu</option>
                  </select>
                </div>

                <div>
                  <label className="text-xs font-bold text-slate-600 block mb-1">
                    Bilangan Soalan: ({count})
                  </label>
                  <input
                    type="range"
                    min={5}
                    max={25}
                    step={1}
                    value={count}
                    onChange={(e) => setCount(parseInt(e.target.value, 10))}
                    className="w-full accent-amber-500"
                  />
                </div>

                <div>
                  <label className="text-xs font-bold text-slate-600 block mb-1">Tahap Kesukaran (Difficulty)</label>
                  <select
                    value={difficulty}
                    onChange={(e) => setDifficulty(e.target.value as Difficulty)}
                    className="w-full bg-slate-50 border-2 border-slate-200 rounded-xl px-3 py-2 text-sm text-slate-900 focus:outline-none focus:border-amber-500 focus:bg-white"
                  >
                    <option value="Easy">Mudah (Easy)</option>
                    <option value="Medium">Sederhana (Medium)</option>
                    <option value="Hard">Mencabar (Hard)</option>
                    <option value="Mixed">Campuran (Mixed)</option>
                  </select>
                </div>

                <div>
                  <label className="text-xs font-bold text-slate-600 block mb-1">Jenis Soalan (Question Type)</label>
                  <select
                    value={questionType}
                    onChange={(e) => setQuestionType(e.target.value as any)}
                    className="w-full bg-slate-50 border-2 border-slate-200 rounded-xl px-3 py-2 text-sm text-slate-900 focus:outline-none focus:border-amber-500 focus:bg-white"
                  >
                    <option value="MIXED">Campuran (MCQ, Betul/Salah, Jawapan Pendek)</option>
                    <option value="MCQ">Aneka Pilihan Sahaja (MCQ)</option>
                    <option value="TRUE_FALSE">Benar atau Palsu Sahaja</option>
                    <option value="SHORT_ANSWER">Jawapan Pendek Sahaja</option>
                  </select>
                </div>

                <div>
                  <label className="text-xs font-bold text-slate-600 block mb-1">
                    Kod Kurikulum / Standard (Pilihan)
                  </label>
                  <input
                    type="text"
                    value={curriculumStandard}
                    onChange={(e) => setCurriculumStandard(e.target.value)}
                    placeholder="cth. KSSR Semakan / DSKP"
                    className="w-full bg-slate-50 border-2 border-slate-200 rounded-xl px-3 py-2 text-sm text-slate-900 focus:outline-none focus:border-amber-500 focus:bg-white"
                  />
                </div>
              </div>

              {/* Checkboxes */}
              <div className="flex flex-wrap gap-4 pt-2">
                <label className="flex items-center gap-2 text-xs font-semibold text-slate-700 cursor-pointer">
                  <input
                    type="checkbox"
                    checked={includeExplanations}
                    onChange={(e) => setIncludeExplanations(e.target.checked)}
                    className="w-4 h-4 rounded text-amber-500 accent-amber-500"
                  />
                  <span>Sertakan penerangan jawapan pembelajaran</span>
                </label>
                <label className="flex items-center gap-2 text-xs font-semibold text-slate-700 cursor-pointer">
                  <input
                    type="checkbox"
                    checked={includeAlternatives}
                    onChange={(e) => setIncludeAlternatives(e.target.checked)}
                    className="w-4 h-4 rounded text-amber-500 accent-amber-500"
                  />
                  <span>Sertakan variasi jawapan yang diterima untuk soalan pendek</span>
                </label>
              </div>

              {errorMessage && (
                <div className="p-3.5 bg-rose-50 border-2 border-rose-300 rounded-xl text-xs font-bold text-rose-800">
                  {errorMessage}
                </div>
              )}
            </div>
          ) : (
            /* Review & Edit Screen */
            <div className="space-y-4">
              <div className="flex items-center justify-between pb-3 border-b border-slate-200">
                <input
                  type="text"
                  value={quizTitle}
                  onChange={(e) => setQuizTitle(e.target.value)}
                  className="text-lg font-black text-slate-900 bg-white border-b-2 border-amber-500 focus:outline-none py-1 flex-1 mr-4"
                />
                <span className="text-xs font-black text-amber-600 bg-amber-50 px-2.5 py-1 rounded-lg border border-amber-200 shrink-0">
                  {generatedQuestions.length} Soalan Dijana
                </span>
              </div>

              {/* List of reviewable questions */}
              <div className="space-y-3 max-h-[500px] overflow-y-auto pr-2">
                {generatedQuestions.map((q, qIndex) => (
                  <div
                    key={q.id || qIndex}
                    className="p-4 bg-slate-50 border-2 border-slate-200 rounded-2xl space-y-3 shadow-xs"
                  >
                    <div className="flex items-start justify-between gap-3">
                      <div className="flex-1">
                        <div className="flex items-center gap-2 mb-1.5">
                          <span className="text-xs font-black text-slate-500 uppercase">
                            Soalan {qIndex + 1} &bull; {q.type} &bull; {q.difficulty}
                          </span>
                        </div>
                        <input
                          type="text"
                          value={q.question}
                          onChange={(e) => handleUpdateQuestion(qIndex, { question: e.target.value })}
                          className="w-full bg-white border-2 border-slate-200 rounded-lg px-3 py-1.5 text-sm font-bold text-slate-900 focus:outline-none focus:border-amber-500"
                        />
                      </div>
                      <button
                        type="button"
                        onClick={() => handleDeleteQuestion(qIndex)}
                        className="p-1.5 text-slate-400 hover:text-rose-600 cursor-pointer"
                        title="Padam soalan"
                      >
                        <Trash2 className="w-4 h-4" />
                      </button>
                    </div>

                    {/* MCQ Options */}
                    {q.type === 'MCQ' && (
                      <div className="grid grid-cols-1 sm:grid-cols-2 gap-2 text-xs">
                        {q.options.map((opt, oIndex) => (
                          <div key={opt.label} className="flex items-center gap-1.5">
                            <span
                              className={`w-6 h-6 rounded flex items-center justify-center font-black ${
                                q.correctAnswer === opt.label
                                  ? 'bg-amber-500 text-slate-950 shadow-xs'
                                  : 'bg-slate-200 text-slate-700'
                              }`}
                            >
                              {opt.label}
                            </span>
                            <input
                              type="text"
                              value={opt.text}
                              onChange={(e) => {
                                const newOpts = [...q.options];
                                newOpts[oIndex] = { ...newOpts[oIndex], text: e.target.value };
                                handleUpdateQuestion(qIndex, { options: newOpts });
                              }}
                              className="flex-1 bg-white border border-slate-300 rounded px-2.5 py-1 text-slate-800 font-medium focus:outline-none focus:border-amber-500"
                            />
                          </div>
                        ))}
                      </div>
                    )}

                    {/* Correct Answer & Explanation */}
                    <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 pt-1 text-xs">
                      <div>
                        <span className="text-slate-600 font-bold block mb-0.5">Jawapan Betul:</span>
                        <input
                          type="text"
                          value={q.correctAnswer}
                          onChange={(e) => handleUpdateQuestion(qIndex, { correctAnswer: e.target.value })}
                          className="w-full bg-white border border-slate-300 rounded px-2.5 py-1 text-emerald-700 font-black focus:outline-none focus:border-amber-500"
                        />
                      </div>
                      <div>
                        <span className="text-slate-600 font-bold block mb-0.5">Penerangan:</span>
                        <input
                          type="text"
                          value={q.explanation}
                          onChange={(e) => handleUpdateQuestion(qIndex, { explanation: e.target.value })}
                          className="w-full bg-white border border-slate-300 rounded px-2.5 py-1 text-slate-700 font-medium focus:outline-none focus:border-amber-500"
                        />
                      </div>
                    </div>
                  </div>
                ))}
              </div>
            </div>
          )}
        </div>

        {/* Footer Actions */}
        <div className="px-6 py-4 border-t border-slate-200 bg-slate-50 flex items-center justify-between gap-3">
          {isReviewing ? (
            <>
              <button
                type="button"
                onClick={() => setIsReviewing(false)}
                className="px-4 py-2.5 rounded-xl text-xs font-bold text-slate-600 hover:text-slate-900 cursor-pointer"
              >
                &larr; Kembali ke Borang
              </button>
              <div className="flex items-center gap-3">
                <button
                  type="button"
                  onClick={handleSaveToLibrary}
                  className="px-5 py-2.5 rounded-xl text-xs font-black bg-amber-500 hover:bg-amber-400 text-slate-950 shadow-md cursor-pointer transition flex items-center gap-1.5"
                >
                  <Save className="w-4 h-4" />
                  <span>Simpan ke Koleksi Kuiz</span>
                </button>
              </div>
            </>
          ) : (
            <>
              <button
                type="button"
                onClick={onCancel}
                className="px-4 py-2.5 rounded-xl text-xs font-semibold text-slate-600 hover:text-slate-900 cursor-pointer"
              >
                Batal / Cancel
              </button>
              <button
                type="button"
                disabled={isGenerating}
                onClick={handleGenerate}
                className={`px-6 py-2.5 rounded-xl text-xs font-black shadow-md cursor-pointer transition flex items-center gap-2 ${
                  isGenerating
                    ? 'bg-slate-200 text-slate-400 cursor-not-allowed'
                    : 'bg-amber-500 hover:bg-amber-400 text-slate-950 active:scale-95'
                }`}
              >
                {isGenerating ? (
                  <>
                    <Loader2 className="w-4 h-4 animate-spin text-slate-950" />
                    <span>Menjana Soalan Menggunakan AI...</span>
                  </>
                ) : (
                  <>
                    <Sparkles className="w-4 h-4" />
                    <span>Jana Kuiz Sekarang</span>
                  </>
                )}
              </button>
            </>
          )}
        </div>
      </div>
    </div>
  );
};
